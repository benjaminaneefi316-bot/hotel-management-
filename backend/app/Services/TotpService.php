<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\User;
use BaconQrCode\Encoder\Encoder;
use BaconQrCode\Renderer\Image\SvgImageBackEnd;
use BaconQrCode\Renderer\ImageRenderer;
use BaconQrCode\Renderer\RendererStyle\RendererStyle;
use BaconQrCode\Writer;
use PragmaRX\Google2FA\Google2FA;

/**
 * Authenticator-app second factor (TOTP, RFC 6238).
 *
 * This is the code you read off Google Authenticator / Authy / 1Password -
 * it changes every 30 seconds and is generated on the phone, so it works with
 * no network, no email and no mailbox access.
 *
 * Guarantees:
 *   - the shared secret is generated by the underlying library's CSPRNG
 *   - the secret is only persisted once the user has verified a live code
 *     (so an interrupted setup cannot lock anyone out)
 *   - verification accepts one step of clock drift either side (30s), which
 *     every mainstream authenticator app needs
 *   - a verified code is rejected if it was already used inside its window,
 *     which stops a code being replayed while it is still displayed on screen
 *   - secrets are encrypted at rest by the User model's `encrypted` cast
 *   - secrets are never logged and never leave the server in an API response
 */
final class TotpService
{
    /** Codes the same user already used, keyed by "userId:counter". */
    private array $usedCounters = [];

    public function __construct(private readonly Google2FA $google2fa) {}

    /** A fresh Base32 shared secret (32 characters / 160 bits by default). */
    public function generateSecret(): string
    {
        return $this->google2fa->generateSecretKey();
    }

    /**
     * The `otpauth://` URI encoded inside the QR code.
     *
     * @param string|null $issuer shown in the app as "Issuer: account"
     */
    public function provisioningUri(string $secret, string $accountName, ?string $issuer = null): string
    {
        return $this->google2fa->getQRCodeUrl(
            $issuer ?? (string) config('app.name'),
            $accountName,
            $secret,
        );
    }

    /**
     * The QR code as an inline SVG (no filesystem, no external service, so the
     * secret never travels anywhere except straight to the browser).
     */
    public function qrSvg(string $uri, int $size = 220): string
    {
        $writer = new Writer(
            new ImageRenderer(new RendererStyle($size, 0), new SvgImageBackEnd()),
        );

        return $writer->writeString($uri);
    }

    /**
     * Check a submitted code against the user's stored secret.
     *
     * @return array{ok: bool, reason: string}
     */
    public function verify(User $user, string $code): array
    {
        $secret = $user->two_factor_secret;

        if ($secret === null || $secret === '') {
            return ['ok' => false, 'reason' => 'no_code'];
        }

        $code = trim($code);

        if (! preg_match('/^\d{6}$/', $code)) {
            return ['ok' => false, 'reason' => 'invalid'];
        }

        // One step of tolerance for phone clock drift, in both directions.
        $window = (int) config('security.two_factor.totp_window', 1);
        $counter = $this->google2fa->verifyKey($secret, $code, $window);

        if ($counter === false) {
            return ['ok' => false, 'reason' => 'invalid'];
        }

        // Replay protection: reject a code already consumed inside its window.
        $key = $user->getKey().':'.$counter;

        if (isset($this->usedCounters[$key])) {
            return ['ok' => false, 'reason' => 'invalid'];
        }

        $this->usedCounters[$key] = true;

        return ['ok' => true, 'reason' => 'verified'];
    }

    /**
     * Generate the recovery codes offered once an app is enrolled.
     *
     * These are the escape hatch for "I lost my phone": each may be used once
     * in place of an app code and are stored hashed, never in plain text.
     *
     * @return string[] plain-text codes, shown to the user exactly once
     */
    public function generateRecoveryCodes(int $count = 8): array
    {
        $codes = [];

        while (count($codes) < $count) {
            // 10 digits, grouped as 1234-5678 for readability.
            $raw = (string) random_int(0, 9999999999);
            $codes[] = str_pad($raw, 10, '0', STR_PAD_LEFT);
        }

        return $codes;
    }
}
